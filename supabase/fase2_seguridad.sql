create or replace function public.auditar_cambio()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  anterior jsonb;
  nuevo jsonb;
  registro_id uuid;
  campos_sensibles text[] := array[
    'password', 'token_hash', 'email', 'documento', 'direccion', 'telefono',
    'peso', 'peso_actual', 'estatura', 'cintura', 'cadera', 'imc', 'icc',
    'observaciones'
  ];
begin
  anterior := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) - campos_sensibles else null end;
  nuevo := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) - campos_sensibles else null end;
  registro_id := nullif(coalesce(nuevo ->> 'id', anterior ->> 'id'), '')::uuid;

  insert into public.auditoria (
    actor_id, accion, entidad, entidad_id, datos_anteriores, datos_nuevos
  ) values (
    auth.uid(), lower(tg_op), tg_table_name, registro_id, anterior, nuevo
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

-- 4. Invitaciones administrativas.
create or replace function public.crear_invitacion_admin(
  p_email text,
  p_dias_vigencia integer default 7
)
returns table(invitacion_id uuid, codigo text, vence_en timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
  correo_normalizado text := lower(trim(coalesce(p_email, '')));
  codigo_generado text;
  id_generado uuid;
  fecha_vencimiento timestamptz;
begin
  if not public.usuario_activo_con_rol('admin') then
    raise exception 'Solo un administrador activo puede crear invitaciones';
  end if;
  if correo_normalizado !~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$' then
    raise exception 'El correo de la invitacion no es valido';
  end if;
  if p_dias_vigencia < 1 or p_dias_vigencia > 30 then
    raise exception 'La vigencia debe estar entre 1 y 30 dias';
  end if;
  if exists (
    select 1 from public.usuarios
    where lower(email) = correo_normalizado
      and rol = 'admin'::public.rol_usuario
      and estado = 'activo'::public.estado_usuario
  ) then
    raise exception 'El correo ya pertenece a un administrador activo';
  end if;

  update public.invitaciones_admin as i
  set estado = 'vencida'
  where i.estado = 'pendiente' and i.vence_en <= now();

  update public.invitaciones_admin as i
  set estado = 'revocada', revocado_en = now()
  where lower(i.email) = correo_normalizado and i.estado = 'pendiente';

  codigo_generado := upper(encode(extensions.gen_random_bytes(12), 'hex'));
  fecha_vencimiento := now() + make_interval(days => p_dias_vigencia);

  insert into public.invitaciones_admin (
    email, token_hash, creado_por, vence_en
  ) values (
    correo_normalizado,
    encode(extensions.digest(convert_to(codigo_generado, 'UTF8'), 'sha256'), 'hex'),
    auth.uid(),
    fecha_vencimiento
  ) returning id into id_generado;

  return query select id_generado, codigo_generado, fecha_vencimiento;
end;
$$;

create or replace function public.validar_invitacion_admin(
  p_email text,
  p_codigo text
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.invitaciones_admin i
    where lower(i.email) = lower(trim(coalesce(p_email, '')))
      and i.token_hash = encode(
        extensions.digest(convert_to(upper(trim(coalesce(p_codigo, ''))), 'UTF8'), 'sha256'),
        'hex'
      )
      and i.estado = 'pendiente'
      and i.vence_en > now()
  );
$$;

create or replace function public.revocar_invitacion_admin(p_invitacion_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.usuario_activo_con_rol('admin') then
    raise exception 'Solo un administrador activo puede revocar invitaciones';
  end if;

  update public.invitaciones_admin
  set estado = 'revocada', revocado_en = now()
  where id = p_invitacion_id
    and estado = 'pendiente';

  return found;
end;
$$;

-- 5. El trigger de Auth valida las invitaciones y conserva el rol solicitado.
create or replace function public.crear_perfil_desde_auth(
  usuario_id uuid,
  correo text,
  metadatos jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  perfil jsonb := coalesce(metadatos -> 'perfil_aplicacion', '{}'::jsonb);
  rol_meta text := lower(coalesce(metadatos -> 'perfil_aplicacion' ->> 'rol', 'coach'));
  tipo_documento_meta text := lower(coalesce(metadatos -> 'perfil_aplicacion' ->> 'tipo_documento', 'cedula'));
  codigo_invitacion text := upper(trim(coalesce(metadatos -> 'perfil_aplicacion' ->> 'codigo_invitacion_admin', '')));
  correo_normalizado text := lower(trim(coalesce(correo, perfil ->> 'email', '')));
  rol_pedido public.rol_usuario := 'coach'::public.rol_usuario;
  invitacion_id uuid;
  nombre_perfil text;
begin
  nombre_perfil := coalesce(
    nullif(trim(perfil ->> 'nombre'), ''),
    nullif(split_part(correo_normalizado, '@', 1), ''),
    'Usuario'
  );

  if rol_meta = 'admin' then
    select i.id into invitacion_id
    from public.invitaciones_admin i
    where lower(i.email) = correo_normalizado
      and i.token_hash = encode(
        extensions.digest(convert_to(codigo_invitacion, 'UTF8'), 'sha256'),
        'hex'
      )
      and i.estado = 'pendiente'
      and i.vence_en > now()
    for update;

    if invitacion_id is null then
      raise exception 'INVITACION_ADMIN_INVALIDA';
    end if;
    rol_pedido := 'admin'::public.rol_usuario;
  end if;

  insert into public.usuarios (
    id, nombre, apellido, email, rol, rol_solicitado, estado, codigo,
    telefono, tipo_documento, documento, direccion
  ) values (
    usuario_id,
    nombre_perfil,
    coalesce(trim(perfil ->> 'apellido'), ''),
    correo_normalizado,
    'coach'::public.rol_usuario,
    rol_pedido,
    'pendiente'::public.estado_usuario,
    coalesce(
      nullif(trim(perfil ->> 'codigo'), ''),
      (case when rol_pedido = 'admin' then 'ADMIN-' else 'COACH-' end) ||
        upper(substr(encode(extensions.gen_random_bytes(6), 'hex'), 1, 6))
    ),
    nullif(trim(perfil ->> 'telefono'), ''),
    case
      when tipo_documento_meta = 'pasaporte' then 'pasaporte'::public.tipo_documento_identidad
      else 'cedula'::public.tipo_documento_identidad
    end,
    nullif(trim(perfil ->> 'documento'), ''),
    nullif(trim(perfil ->> 'direccion'), '')
  )
  on conflict (id) do nothing;

  if invitacion_id is not null then
    update public.invitaciones_admin
    set estado = 'utilizada', usado_por = usuario_id, usado_en = now()
    where id = invitacion_id;
  end if;
end;
$$;

-- 6. Las decisiones se realizan mediante RPC y no con UPDATE directo.
create or replace function public.resolver_solicitud(
  p_usuario_id uuid,
  p_decision text,
  p_motivo text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  objetivo public.usuarios%rowtype;
  decision text := lower(trim(coalesce(p_decision, '')));
  motivo text := nullif(trim(coalesce(p_motivo, '')), '');
begin
  if not public.usuario_activo_con_rol('admin') then
    raise exception 'Solo un administrador activo puede resolver solicitudes';
  end if;

  select * into objetivo
  from public.usuarios
  where id = p_usuario_id
  for update;

  if not found then raise exception 'La solicitud no existe'; end if;
  if objetivo.id = auth.uid() then raise exception 'No puedes resolver tu propia cuenta'; end if;

  if decision = 'aprobar' then
    if objetivo.estado <> 'pendiente'::public.estado_usuario then
      raise exception 'Solo se pueden aprobar solicitudes pendientes';
    end if;
    update public.usuarios
    set rol = coalesce(rol_solicitado, rol),
        estado = 'activo'::public.estado_usuario,
        aprobado_por = auth.uid(),
        decision_en = now(),
        motivo_decision = motivo
    where id = p_usuario_id;
  elsif decision = 'rechazar' then
    if objetivo.estado <> 'pendiente'::public.estado_usuario then
      raise exception 'Solo se pueden rechazar solicitudes pendientes';
    end if;
    if motivo is null or length(motivo) < 3 then
      raise exception 'Debes indicar el motivo del rechazo';
    end if;
    update public.usuarios
    set estado = 'rechazado'::public.estado_usuario,
        aprobado_por = auth.uid(),
        decision_en = now(),
        motivo_decision = motivo
    where id = p_usuario_id;
  elsif decision = 'reabrir' then
    if objetivo.estado <> 'rechazado'::public.estado_usuario then
      raise exception 'Solo se pueden reabrir solicitudes rechazadas';
    end if;
    update public.usuarios
    set estado = 'pendiente'::public.estado_usuario,
        aprobado_por = auth.uid(),
        decision_en = now(),
        motivo_decision = coalesce(motivo, 'Solicitud reabierta para revisión')
    where id = p_usuario_id;
  else
    raise exception 'Decision no permitida';
  end if;

  return (
    select jsonb_build_object(
      'id', u.id,
      'rol', u.rol,
      'rol_solicitado', u.rol_solicitado,
      'estado', u.estado,
      'decision_en', u.decision_en
    )
    from public.usuarios u
    where u.id = p_usuario_id
  );
end;
$$;

create or replace function public.resolver_solicitudes(
  p_usuarios uuid[],
  p_decision text,
  p_motivo text default null
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  usuario_id uuid;
  cantidad integer := 0;
begin
  if not public.usuario_activo_con_rol('admin') then
    raise exception 'Solo un administrador activo puede resolver solicitudes';
  end if;
  if coalesce(array_length(p_usuarios, 1), 0) = 0 then return 0; end if;

  foreach usuario_id in array p_usuarios
  loop
    perform public.resolver_solicitud(usuario_id, p_decision, p_motivo);
    cantidad := cantidad + 1;
  end loop;
  return cantidad;
end;
$$;

create or replace function public.cambiar_estado_usuario(
  p_usuario_id uuid,
  p_estado text,
  p_motivo text default null
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  objetivo public.usuarios%rowtype;
  estado_nuevo text := lower(trim(coalesce(p_estado, '')));
begin
  if not public.usuario_activo_con_rol('admin') then
    raise exception 'Solo un administrador activo puede cambiar estados';
  end if;
  if estado_nuevo not in ('activo', 'inactivo') then
    raise exception 'Estado no permitido';
  end if;

  select * into objetivo from public.usuarios where id = p_usuario_id for update;
  if not found then raise exception 'La cuenta no existe'; end if;
  if objetivo.id = auth.uid() and estado_nuevo = 'inactivo' then
    raise exception 'No puedes desactivar tu propia cuenta';
  end if;
  if objetivo.rol = 'admin'::public.rol_usuario and estado_nuevo = 'inactivo' and (
    select count(*) from public.usuarios
    where rol = 'admin'::public.rol_usuario and estado = 'activo'::public.estado_usuario
  ) <= 1 then
    raise exception 'No se puede desactivar el ultimo administrador activo';
  end if;

  update public.usuarios
  set estado = estado_nuevo::public.estado_usuario,
      aprobado_por = auth.uid(),
      decision_en = now(),
      motivo_decision = nullif(trim(coalesce(p_motivo, '')), '')
  where id = p_usuario_id;

  return true;
end;
$$;

-- 7. Reglas de integridad entre entrenadores, clientes, rutinas y eventos.
create or replace function public.validar_propiedad_cliente()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  coach_rutina uuid;
begin
  if new.coach_id is not null and not exists (
    select 1 from public.usuarios u
    where u.id = new.coach_id
      and u.rol = 'coach'::public.rol_usuario
      and u.estado = 'activo'::public.estado_usuario
  ) then
    raise exception 'El entrenador asignado no existe o no esta activo';
  end if;

  if new.rutina_id is not null then
    select r.coach_id into coach_rutina from public.rutinas r where r.id = new.rutina_id;
    if coach_rutina is null or new.coach_id is null or coach_rutina <> new.coach_id then
      raise exception 'La rutina no pertenece al entrenador del cliente';
    end if;
  end if;
  return new;
end;
$$;

create or replace function public.validar_propiedad_evento()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.cliente_id is not null and not exists (
    select 1 from public.clientes c
    where c.id = new.cliente_id and c.coach_id = new.coach_id
  ) then
    raise exception 'El cliente del evento no pertenece al entrenador';
  end if;
  return new;
end;
$$;

create or replace function public.validar_propiedad_medicion()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.clientes c
    where c.id = new.cliente_id and c.coach_id = new.coach_id
  ) then
    raise exception 'El cliente de la medicion no pertenece al entrenador';
  end if;
  return new;
end;
$$;

drop trigger if exists validar_cliente_propiedad on public.clientes;
create trigger validar_cliente_propiedad
before insert or update of coach_id, rutina_id on public.clientes
for each row execute function public.validar_propiedad_cliente();

drop trigger if exists validar_evento_propiedad on public.eventos;
create trigger validar_evento_propiedad
before insert or update of coach_id, cliente_id on public.eventos
for each row execute function public.validar_propiedad_evento();

drop trigger if exists validar_medicion_propiedad on public.mediciones;
create trigger validar_medicion_propiedad
before insert or update of coach_id, cliente_id on public.mediciones
for each row execute function public.validar_propiedad_medicion();

-- 8. Triggers de auditoria.
